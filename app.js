function seekTo(seconds) {
  seconds = Math.max(
    0,
    Math.min(
      duration || 0,
      seconds
    )
  );

  pausedAt = seconds;

  if (isPlaying) {
    startAt(seconds);
  } else {
    updateProgress();
  }
}

function nextTrack() {
  if (!currentPlaylist.length) {
    return;
  }

  // Se ainda houver outra faixa no álbum/playlist atual, toca a próxima.
  if (currentTrackIndex < currentPlaylist.length - 1) {
    currentTrackIndex++;

    renderTrackList();
    updateAlbumUI();
    loadCurrentTrack(true);
    return;
  }

  // No modo All Songs / Shuffle, ao terminar,
  // embaralha tudo novamente e continua tocando.
  if (isShufflePlaylist) {
    currentPlaylist = getAllTracksShuffled();
    currentTrackIndex = 0;

    renderTrackList();
    updateAlbumUI();
    loadCurrentTrack(true);
    return;
  }

  // Terminou um álbum normal:
  // vai para o próximo álbum automaticamente.
  // Se era o último, volta para o primeiro.
  currentAlbumIndex =
    (currentAlbumIndex + 1) % ALBUMS.length;

  currentTrackIndex = 0;

  const nextAlbum = ALBUMS[currentAlbumIndex];

  currentPlaylist = nextAlbum.tracks.map((track, trackIndex) => ({
    ...track,
    albumTitle: nextAlbum.title,
    albumCover: nextAlbum.cover,
    originalAlbumIndex: currentAlbumIndex,
    originalTrackIndex: trackIndex
  }));

  currentPlaylistTitle = nextAlbum.title;
  currentPlaylistCover = nextAlbum.cover;
  isShufflePlaylist = false;

  renderTrackList();
  updateAlbumUI();
  loadCurrentTrack(true);
}

function prevTrack() {
  if (!currentPlaylist.length) {
    return;
  }

  currentTrackIndex =
    (
      currentTrackIndex -
      1 +
      currentPlaylist.length
    ) %
    currentPlaylist.length;

  renderTrackList();
  updateAlbumUI();
  loadCurrentTrack(true);
}

