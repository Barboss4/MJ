// Os arquivos do bucket estão dentro da pasta "all".
// Esta URL é pública e pode ficar no JavaScript do site.
// NÃO coloque Access Key ID, Secret Access Key ou API Token aqui.
const R2_MEDIA_BASE =
  "https://pub-06b4533c184f435ba5edce9d544344fe.r2.dev/all";

function getR2Url(localUrl) {
  const localPrefix = "assets/audio/all/";

  // Se futuramente alguma URL já for absoluta, mantém como está.
  if (/^https?:\/\//i.test(localUrl)) {
    return localUrl;
  }

  // Só converte os arquivos que pertenciam à pasta local de mídia.
  if (!localUrl.startsWith(localPrefix)) {
    return localUrl;
  }

  const relativePath = localUrl.slice(localPrefix.length);

  // Codifica cada parte do caminho individualmente. Isso evita problemas
  // caso algum nome de arquivo futuro tenha espaço, #, %, acentos etc.
  const encodedPath = relativePath
    .split("/")
    .map(part => encodeURIComponent(part))
    .join("/");

  return `${R2_MEDIA_BASE}/${encodedPath}`;
}

// Converte automaticamente TODAS as capas, versões completas e
// instrumentais para a URL pública do R2. Assim o bloco ALBUMS continua
// fácil de gerar e manter usando os caminhos locais originais.
for (const album of ALBUMS) {
  album.cover = getR2Url(album.cover);

  for (const track of album.tracks) {
    track.vocalUrl = getR2Url(track.vocalUrl);
    track.instrumentalUrl = getR2Url(track.instrumentalUrl);
  }
}



