function formatTime(sec) {
  if (!Number.isFinite(sec)) {
    return "0:00";
  }

  const m = Math.floor(sec / 60);
  const s = Math.floor(sec % 60);

  return `${m}:${String(s).padStart(2, "0")}`;
}

function updateProgress() {
  const pos = getPosition();

  currentTimeEl.textContent =
    formatTime(pos);

  seek.value =
    duration > 0
      ? Math.round(
          (pos / duration) * 1000
        )
      : 0;
}

