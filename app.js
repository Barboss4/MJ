// ============================================================

function applyMode(
  atTime = audioCtx?.currentTime || 0,
  instant = false
) {
  if (!vocalGain || !instGain) {
    return;
  }

  const crossfade = instant ? 0 : 0.012;

  vocalGain.gain.cancelScheduledValues(atTime);
  instGain.gain.cancelScheduledValues(atTime);

  const vocalTarget =
    mode === "full" ? 1 : 0;

  const instTarget =
    mode === "instrumental" ? 1 : 0;

  if (crossfade === 0) {
    vocalGain.gain.setValueAtTime(
      vocalTarget,
      atTime
    );

    instGain.gain.setValueAtTime(
      instTarget,
      atTime
    );
  } else {
    vocalGain.gain.setValueAtTime(
      vocalGain.gain.value,
      atTime
    );

    instGain.gain.setValueAtTime(
      instGain.gain.value,
      atTime
    );

    vocalGain.gain.linearRampToValueAtTime(
      vocalTarget,
      atTime + crossfade
    );

    instGain.gain.linearRampToValueAtTime(
      instTarget,
      atTime + crossfade
    );
  }

  fullBtn.classList.toggle(
    "active",
    mode === "full"
  );

  instBtn.classList.toggle(
    "active",
    mode === "instrumental"
  );

  syncStatus.textContent =
    mode === "full"
      ? "Com voz • mesma posição temporal"
      : "Instrumental • mesma posição temporal";
}

function setMode(nextMode) {
  mode = nextMode;

  if (audioCtx) {
    applyMode(audioCtx.currentTime);
  } else {
    fullBtn.classList.toggle(
      "active",
      mode === "full"
    );

    instBtn.classList.toggle(
      "active",
      mode === "instrumental"
    );
  }

  if (miniStemSwitch) {
    miniStemSwitch.checked = mode === "instrumental";
  }
}

