async function ensureAudio() {
  if (!audioCtx) {
    audioCtx = new (
      window.AudioContext ||
      window.webkitAudioContext
    )();

    masterGain = audioCtx.createGain();
    masterGain.gain.value = volume;
    vocalGain = audioCtx.createGain();
    instGain = audioCtx.createGain();

    analyser = audioCtx.createAnalyser();
    analyser.fftSize = 256;

    vocalGain.connect(masterGain);
    instGain.connect(masterGain);

    masterGain.connect(analyser);
    analyser.connect(audioCtx.destination);
  }

  if (audioCtx.state === "suspended") {
    await audioCtx.resume();
  }
}

async function decodeUrl(url) {
  const response = await fetch(url);

  if (!response.ok) {
    throw new Error(`Não foi possível carregar ${url}`);
  }

  const data = await response.arrayBuffer();

  return await audioCtx.decodeAudioData(data);
}

async function loadCurrentTrack(autoPlay) {
  const track = getCurrentTrack();

  if (!track) {
    return;
  }

  const token = ++loadToken;

  stopSources();

  pausedAt = 0;
  seek.value = 0;

  currentTimeEl.textContent = "0:00";
  durationEl.textContent = "0:00";
  syncStatus.textContent = "Carregando as duas versões…";

  playBtn.disabled = true;

  try {
    await ensureAudio();

    const [v, i] = await Promise.all([
      decodeUrl(track.vocalUrl),
      decodeUrl(track.instrumentalUrl)
    ]);

    if (token !== loadToken) {
      return;
    }

    vocalBuffer = v;
    instBuffer = i;

    duration = Math.min(
      vocalBuffer.duration,
      instBuffer.duration
    );

    durationEl.textContent = formatTime(duration);
    playBtn.disabled = false;

    const mismatch = Math.abs(
      vocalBuffer.duration - instBuffer.duration
    );

    syncStatus.textContent =
      mismatch < 0.02
        ? `Prontas • diferença de duração ${mismatch.toFixed(3)} s`
        : `Atenção: as versões diferem ${mismatch.toFixed(3)} s`;

    if (autoPlay) {
      startAt(0);
    }
  } catch (err) {
    vocalBuffer = null;
    instBuffer = null;
    duration = 0;

    playBtn.disabled = false;

    syncStatus.textContent =
      "Não foi possível carregar os arquivos de áudio.";

    console.warn(err);
  }
}

function createSource(buffer, gain) {
  const source = audioCtx.createBufferSource();

  source.buffer = buffer;
  source.connect(gain);

  return source;
}

async function startAt(offset) {
  await ensureAudio();

  if (!vocalBuffer || !instBuffer) {
    syncStatus.textContent =
      "Os arquivos de áudio ainda não foram carregados.";

    return;
  }

  stopSources();

  vocalSource = createSource(
    vocalBuffer,
    vocalGain
  );

  instSource = createSource(
    instBuffer,
    instGain
  );

  // As duas versões começam exatamente no mesmo instante.
  const t = audioCtx.currentTime + 0.035;

  applyMode(t, true);

  vocalSource.start(t, offset);
  instSource.start(t, offset);

  startedAt = t - offset;
  pausedAt = offset;
  isPlaying = true;

  playBtn.textContent = "❚❚";

  updateAlbumUI();

  vocalSource.onended = () => {
    if (
      isPlaying &&
      getPosition() >= duration - 0.05
    ) {
      nextTrack();
    }
  };

  cancelAnimationFrame(raf);

  tick();
}

function pause() {
  if (!isPlaying) {
    return;
  }

  pausedAt = getPosition();
  isPlaying = false;

  stopSources();

  playBtn.textContent = "▶";

  updateAlbumUI();
}

function stopSources() {
  for (const source of [
    vocalSource,
    instSource
  ]) {
    if (source) {
      try {
        source.onended = null;
        source.stop();
      } catch {}

      try {
        source.disconnect();
      } catch {}
    }
  }

  vocalSource = null;
  instSource = null;
}

function getPosition() {
  if (!isPlaying || !audioCtx) {
    return pausedAt || 0;
  }

  return Math.max(
    0,
    Math.min(
      duration,
      audioCtx.currentTime - startedAt
    )
  );
}

