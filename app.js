function drawHeroWave() {
  if (!heroWavePath) {
    return;
  }

  const width = 1600;
  const centerY = 112;
  const points = 180;

  const time =
    performance.now() / 1000;

  let audioEnergy = 0;

  if (analyser && isPlaying) {
    const waveData =
      new Uint8Array(
        analyser.frequencyBinCount
      );

    analyser.getByteTimeDomainData(
      waveData
    );

    let total = 0;

    for (
      let i = 0;
      i < waveData.length;
      i++
    ) {
      total +=
        Math.abs(
          waveData[i] - 128
        ) / 128;
    }

    audioEnergy =
      total / waveData.length;
  }

  const baseAmplitude = 17;
  const reactiveAmplitude =
    audioEnergy * 115;

  const amplitude =
    baseAmplitude +
    reactiveAmplitude;

  let d = "";

  for (
    let i = 0;
    i <= points;
    i++
  ) {
    const x =
      (i / points) * width;

    const y =
      centerY +
      Math.sin(
        i * 0.43 +
          time * 2.3
      ) *
        amplitude *
        0.52 +
      Math.sin(
        i * 0.91 -
          time * 1.65
      ) *
        amplitude *
        0.28 +
      Math.sin(
        i * 0.17 +
          time * 0.85
      ) *
        amplitude *
        0.20;

    d +=
      `${i === 0 ? "M" : "L"}` +
      `${x.toFixed(2)} ` +
      `${y.toFixed(2)} `;
  }

  heroWavePath.setAttribute(
    "d",
    d
  );

  if (
    !window.matchMedia(
      "(prefers-reduced-motion: reduce)"
    ).matches
  ) {
    requestAnimationFrame(
      drawHeroWave
    );
  }
}

