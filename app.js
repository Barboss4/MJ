function drawVisualizer() {
  const dpr = Math.max(
    1,
    window.devicePixelRatio || 1
  );

  const rect =
    canvas.getBoundingClientRect();

  const wantW = Math.max(
    1,
    Math.round(rect.width * dpr)
  );

  const wantH = Math.max(
    1,
    Math.round(rect.height * dpr)
  );

  if (
    canvas.width !== wantW ||
    canvas.height !== wantH
  ) {
    canvas.width = wantW;
    canvas.height = wantH;
  }

  ctx2d.clearRect(
    0,
    0,
    canvas.width,
    canvas.height
  );

  ctx2d.fillStyle = "rgba(255,255,255,.04)";

  ctx2d.fillRect(
    0,
    0,
    canvas.width,
    canvas.height
  );

  ctx2d.strokeStyle = "#8a8680";
  ctx2d.lineWidth = 1.5 * dpr;
  ctx2d.beginPath();

  if (analyser && isPlaying) {
    const data =
      new Uint8Array(
        analyser.frequencyBinCount
      );

    analyser.getByteTimeDomainData(data);

    for (
      let x = 0;
      x < data.length;
      x++
    ) {
      const px =
        (x / (data.length - 1)) *
        canvas.width;

      const py =
        (data[x] / 255) *
        canvas.height;

      if (x === 0) {
        ctx2d.moveTo(px, py);
      } else {
        ctx2d.lineTo(px, py);
      }
    }
  } else {
    const mid =
      canvas.height / 2;

    const t =
      performance.now() / 1000;

    for (
      let x = 0;
      x < canvas.width;
      x += 7 * dpr
    ) {
      const amp =
        (
          7 +
          9 *
            Math.sin(
              (x / canvas.width) *
                Math.PI *
                7 +
                t
            )
        ) *
        dpr;

      const py =
        mid +
        Math.sin(
          x / (18 * dpr) +
            t * 1.3
        ) *
          amp;

      if (x === 0) {
        ctx2d.moveTo(x, py);
      } else {
        ctx2d.lineTo(x, py);
      }
    }
  }

  ctx2d.stroke();
}

function tick() {
  updateProgress();
  drawVisualizer();

  if (isPlaying) {
    raf = requestAnimationFrame(tick);
  }
}

